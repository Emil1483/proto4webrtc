def _block(rec: _MsgRec, registry: _Registry) -> _Block:
    if rec.desc.oneof_decl:
        # A faithful translation needs a discriminator convention, and silently
        # flattening a oneof into always-present fields loses the invariant that
        # exactly one is set. Refuse rather than generate something misleading.
        raise Ros2GenError(
            f"{rec.file}:{rec.ros_name}: `oneof` has no ROS2 interface "
            f"equivalent. Restructure the message, or leave this file out of "
            f"include=."
        )
    return _Block(fields=[_field(f, rec, registry) for f in rec.desc.field])


def _field(f, rec: _MsgRec, registry: _Registry) -> _Field:
    where = f"{rec.file}:{rec.ros_name}.{f.name}"
    if not _ROS_FIELD_RE.match(f.name):
        raise Ros2GenError(
            f"{where}: not a valid ROS2 field name (must be lower_snake_case); "
            f"rename it in the .proto"
        )
    if f.name in _RESERVED_FIELD_NAMES:
        raise Ros2GenError(
            f"{where}: `{f.name}` is a C++/Python keyword, so rosidl would "
            f"generate code that does not compile; rename it in the .proto"
        )
    repeated = f.label == _LABEL_REPEATED
    suffix = "[]" if repeated else ""

    if f.type == _MESSAGE:
        if f.type_name in registry.map_entries:
            raise Ros2GenError(
                f"{where}: `map<>` has no ROS2 interface equivalent. Use a "
                f"repeated key/value message instead."
            )
        if f.type_name not in registry.by_fq:
            raise Ros2GenError(
                f"{where}: {f.type_name} is not in the target set (its file is "
                f"left out by include=, it is a well-known type, or it is a "
                f"declaration-only media_stream message). Add its file, or drop "
                f"the field."
            )
        return _Field(registry.by_fq[f.type_name].ros_name + suffix, f.name)

    if f.type == _ENUM:
        if f.type_name not in registry.enums:
            raise Ros2GenError(
                f"{where}: enum {f.type_name} is not in the target set; add its "
                f"file to include=."
            )
        values = registry.enums[f.type_name]
        for value_name, _number in values:
            if not _ROS_CONST_RE.match(value_name):
                raise Ros2GenError(
                    f"{where}: enum value {f.type_name}.{value_name} is not a "
                    f"valid ROS2 constant name (must be UPPER_SNAKE_CASE); "
                    f"rename it in the .proto"
                )
        # The field is an int32; the values become a constants block above it.
        return _Field("int32" + suffix, f.name, enum=(f.type_name, values))

    if f.type == _BYTES:
        if repeated:
            raise Ros2GenError(
                f"{where}: `repeated bytes` would need a nested array, which a "
                f"ROS2 interface cannot express. Wrap it in a message."
            )
        return _Field("uint8[]", f.name)

    try:
        return _Field(_SCALAR[f.type] + suffix, f.name)
    except KeyError:  # pragma: no cover - protoc emits nothing else
        raise Ros2GenError(f"{where}: unsupported proto type {f.type}") from None


def _check_name(name: str, kind: str, source: str, origin: str) -> str:
    """Validate a generated interface name; return it."""
    if not _ROS_TYPE_RE.match(name):
        raise Ros2GenError(
            f"{source}: {origin} would become {kind}/{name}, which is not a "
            f"valid ROS2 interface name (must be CamelCase); rename it in the "
            f".proto"
        )
    return name


def _check_unique(interfaces: list[_Interface]) -> None:
    seen: dict[str, str] = {}
    for i in interfaces:
        if i.rel_path in seen:
            raise Ros2GenError(
                f"duplicate interface {i.rel_path}: from both {seen[i.rel_path]} "
                f"and {i.source}. All proto packages flatten into one ROS2 "
                f"interface package, so the names must be globally unique -- "
                f"rename, or pass --srv-prefix-service for colliding rpcs."
            )
        seen[i.rel_path] = i.source


def _render(interface: _Interface) -> str:
    lines = [
        f"# {GENERATED_MARKER} from {interface.source}. DO NOT EDIT.",
        "#",
        "# Edit the .proto instead; `colcon build` regenerates this directory.",
    ]
    for n, block in enumerate(interface.blocks):
        if n:
            lines.append("---")
        emitted: set[str] = set()
        for f in block.fields:
            if not f.enum or f.enum[0] in emitted:
                continue
            emitted.add(f.enum[0])
            lines.append("")
            lines += [f"int32 {name}={value}" for name, value in f.enum[1]]
        if block.fields:
            lines.append("")
        lines += [f"{f.ros_type} {f.name}" for f in block.fields]
    return "\n".join(lines) + "\n"


def _write(out_dir: Path, interfaces: list[_Interface]) -> list[str]:
    written: set[Path] = set()
    for interface in interfaces:
        path = out_dir / interface.rel_path
        path.parent.mkdir(parents=True, exist_ok=True)
        content = _render(interface)
        written.add(path)
        # Written only on change, so an unchanged proto costs no rosidl rebuild.
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
    # Stale files are removed rather than left behind: an interface deleted from
    # the protos would otherwise linger as a .msg that CMake's glob still picks
    # up and builds. Only our own output is touched -- the marker proves it.
    for sub, pattern in (("msg", "*.msg"), ("srv", "*.srv")):
        directory = out_dir / sub
        if not directory.is_dir():
            continue
        for existing in sorted(directory.glob(pattern)):
            if existing not in written and GENERATED_MARKER in existing.read_text():
                existing.unlink()
    return [i.rel_path for i in interfaces]
