def _find_targets(roots: list[Path], include) -> list[str]:
    """Target proto paths, relative to their root."""
    patterns = None
    if include is not None:
        patterns = [include] if isinstance(include, str) else list(include)

    out: list[str] = []
    for root in roots:
        for path in sorted(root.rglob("*.proto")):
            rel = path.relative_to(root).as_posix()
            if rel == OPTIONS_PROTO:
                continue  # the annotations themselves are never an interface
            if patterns and not any(fnmatch.fnmatch(rel, pat) for pat in patterns):
                continue
            out.append(rel)
    if len(set(out)) != len(out):
        raise Ros2GenError(f"duplicate proto paths across roots {roots}")
    return out


def _compile(roots: list[Path], targets: list[str]) -> descriptor_pb2.FileDescriptorSet:
    """Run protoc, return the parsed FileDescriptorSet."""
    # Imported lazily: grpc_tools is codegen-only, absent from runtime images.
    from grpc_tools import protoc

    from proto4webrtc_codegen.driver import (
        _well_known_include,
        bundled_options_include,
    )

    # The bundled proto4webrtc/options.proto goes on the include path (never as
    # a target), which is what lets the stream annotations resolve without
    # vendoring a second copy into the consumer's tree.
    includes = [str(r) for r in roots] + [
        bundled_options_include(),
        _well_known_include(),
    ]

    with tempfile.TemporaryDirectory() as tmp:
        desc = Path(tmp) / "descriptors.binpb"
        argv = (
            ["protoc"]
            + [f"-I{i}" for i in includes]
            + [f"--descriptor_set_out={desc}", "--include_imports"]
            + list(targets)
        )
        if protoc.main(argv) != 0:
            raise Ros2GenError("protoc failed; see the errors above")
        fdset = descriptor_pb2.FileDescriptorSet()
        fdset.ParseFromString(desc.read_bytes())
    return fdset


class _Registry:
    """What every fully-qualified proto name becomes in the ROS2 package."""

    def __init__(self, fdset: descriptor_pb2.FileDescriptorSet, target_names: set[str]):
        self.messages: list[_MsgRec] = []
        self.by_fq: dict[str, _MsgRec] = {}
        self.map_entries: set[str] = set()
        self.enums: dict[str, tuple[tuple[str, int], ...]] = {}
        self.rpc_messages: dict[str, str] = {}  # fq -> "Service.Method" using it
        self.referenced: set[str] = set()  # fq of every message used as a field type
        self._is_media_stream = _media_stream_check(fdset)

        for file in fdset.file:
            if file.name not in target_names:
                continue  # a resolved import (proto4webrtc/options.proto, wkt, ...)
            scope = f".{file.package}" if file.package else ""
            for enum in file.enum_type:
                self.enums[f"{scope}.{enum.name}"] = tuple(
                    (v.name, v.number) for v in enum.value
                )
            for msg in file.message_type:
                self._walk(msg, scope, "", file.name)

        for rec in self.messages:
            for f in rec.desc.field:
                if f.type == _MESSAGE:
                    self.referenced.add(f.type_name)

        for file in fdset.file:
            if file.name not in target_names:
                continue
            for service in file.service:
                for method in service.method:
                    self._register_rpc(file, service, method)

    def is_payload_only(self, fq: str) -> bool:
        """True for a message that exists *only* to be an rpc payload.

        Those are rendered inside their `.srv` and get no `.msg` of their own: a
        `GetMissionRequest {}` has no meaning as a topic type. Three conditions,
        all required, so the skip never surprises:

        - it is some rpc's request or response type,
        - no other message uses it as a field type (a response that is the
          resource itself -- `rpc GetMission(...) returns (Mission)` alongside a
          `Mission mission` field -- keeps its `.msg`; something needs the type),
        - and it looks like a payload: `*Request`/`*Response` by name, or empty.
          A hand-named message with real fields (`rpc Poke(Status) returns
          (Status)`) is a type in its own right and keeps its `.msg`.
        """
        if fq not in self.rpc_messages or fq in self.referenced:
            return False
        rec = self.by_fq[fq]
        return rec.ros_name.endswith(("Request", "Response")) or not rec.desc.field

    def _walk(self, msg, scope: str, prefix: str, file_name: str) -> None:
        fq = f"{scope}.{msg.name}"
        if msg.options.map_entry:
            self.map_entries.add(fq)  # synthetic entry type for a map<> field
            return
        for enum in msg.enum_type:
            self.enums[f"{fq}.{enum.name}"] = tuple(
                (v.name, v.number) for v in enum.value
            )
        # One flat ROS2 namespace, so a nested message's name is its nested path
        # with the dots removed: pkg.Mission.Waypoint -> MissionWaypoint.
        ros_name = prefix + msg.name
        if not self._is_media_stream(msg):
            rec = _MsgRec(desc=msg, fq=fq, ros_name=ros_name, file=file_name)
            self.messages.append(rec)
            self.by_fq[fq] = rec
        for nested in msg.nested_type:
            self._walk(nested, fq, ros_name, file_name)

    def _register_rpc(self, file, service, method) -> None:
        where = f"{service.name}.{method.name}"
        if method.client_streaming or method.server_streaming:
            raise Ros2GenError(
                f"{file.name}: {where} is streaming, and a ROS2 service is unary. "
                f"Carry the stream on a topic (a plain message) instead."
            )
        for kind, fq in (
            ("request", method.input_type),
            ("response", method.output_type),
        ):
            if fq not in self.by_fq:
                raise Ros2GenError(
                    f"{file.name}: {where} {kind} type {fq} is not in the target "
                    f"set (its file is left out by include=, or it is a "
                    f"well-known type). Add its file, or drop the rpc."
                )
            self.rpc_messages[fq] = where


def _media_stream_check(fdset: descriptor_pb2.FileDescriptorSet):
    """Return is_media_stream(DescriptorProto) -> bool.

    The proto4webrtc options are extensions of google.protobuf.MessageOptions
    that descriptor_pb2 doesn't know, so protoc parks them in the options'
    unknown fields. Re-parsing them against a pool built from the descriptor set
    (which contains proto4webrtc/options.proto -- protoc ran with
    --include_imports) is what surfaces them; the same trick extract.py uses.

    Protos that don't import the options at all are the ordinary case for this
    module -- a ROS user's interface protos need no proto4webrtc annotation -- so
    a set without options.proto is not an error: nothing is a media stream.
    """
    pool = descriptor_pool.DescriptorPool()
    for fdp in fdset.file:  # --include_imports output is dependency-ordered
        pool.Add(fdp)
    try:
        media_ext = pool.FindExtensionByName(MEDIA_STREAM_EXT)
    except KeyError:
        return lambda msg: False
    options_cls = message_factory.GetMessageClass(
        pool.FindMessageTypeByName("google.protobuf.MessageOptions")
    )

    def is_media_stream(msg: descriptor_pb2.DescriptorProto) -> bool:
        opts = options_cls()
        opts.ParseFromString(msg.options.SerializeToString())
        return opts.HasExtension(media_ext)

    return is_media_stream


