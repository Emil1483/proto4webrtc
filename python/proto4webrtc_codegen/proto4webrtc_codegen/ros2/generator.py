def generate_interfaces(
    proto_dirs,
    out_dir,
    include=None,
    services: bool = True,
    srv_prefix_service: bool = False,
) -> list[str]:
    """Render `.msg`/`.srv` files under out_dir; return their relative paths.

    proto_dirs: one dir or a list of dirs; each is a protoc include root.
    out_dir: the ament interface package's directory. `msg/` and `srv/` inside
        it are managed here -- files this generated before but no longer would
        are deleted, and only those (the header marker is what identifies them),
        so hand-written interfaces beside them survive.
    include: optional list of globs (relative to the roots, e.g.
        "telemetry/*.proto"); when given, only matching files become interfaces.
        Non-matching files stay importable, so this is how proto packages no ROS
        node consumes are kept out of the interface package.
    services: render `.srv` files from rpc methods. False emits messages only.
    srv_prefix_service: name srv files `<Service><Method>.srv` instead of
        `<Method>.srv`. Needed when two services share a method name.

    Unchanged files are not rewritten, so an unchanged proto costs no rosidl
    rebuild.
    """
    if isinstance(proto_dirs, (str, Path)):
        proto_dirs = [proto_dirs]
    roots = [Path(d).resolve() for d in proto_dirs]
    for root in roots:
        if not root.is_dir():
            raise Ros2GenError(f"proto root does not exist: {root}")
    out_dir = Path(out_dir).resolve()

    targets = _find_targets(roots, include)
    if not targets:
        raise Ros2GenError(
            f"no .proto files matched under {[str(r) for r in roots]}"
            + (f" with include={include}" if include else "")
        )

    fdset = _compile(roots, targets)
    interfaces = render_interfaces(
        fdset,
        target_names=set(targets),
        services=services,
        srv_prefix_service=srv_prefix_service,
    )
    return _write(out_dir, interfaces)


def render_interfaces(
    fdset: descriptor_pb2.FileDescriptorSet,
    target_names: set[str],
    services: bool = True,
    srv_prefix_service: bool = False,
) -> list[_Interface]:
    """Descriptors -> interface records. The whole mapping, in one place.

    - message -> `msg/<Name>.msg`; nested messages flatten into the parent's
      name (`Mission.Waypoint` -> `MissionWaypoint`), because a ROS2 interface
      package is one flat namespace.
    - `rpc M(MRequest) returns (MResponse)` -> `srv/<M>.srv`, request fields
      inlined above `---`, response fields below. A message that exists only to
      be a payload gets no `.msg` of its own -- see _Registry.is_payload_only()
      for exactly when that applies.
    - proto enum -> an `int32` field plus a constants block, repeated in every
      interface file that uses the enum. That is how ROS2 conventionally
      expresses an enumeration; the value numbers are proto's, unchanged.
    - `bytes` -> `uint8[]`.
    - declaration-only `(proto4webrtc.media_stream)` messages are skipped: RTP
      frames never travel as protobuf, so there is nothing to put in a msg.

    Rejected rather than approximated: `oneof` (loses the exactly-one-set
    invariant), `map<>`, `repeated bytes` (a nested array, inexpressible),
    streaming rpcs, field names that aren't lower_snake_case, references into
    files the target set leaves out, and flattened name collisions.
    """
    registry = _Registry(fdset, target_names)
    out: list[_Interface] = []

    for rec in registry.messages:
        if registry.is_payload_only(rec.fq):
            continue  # rendered inside its .srv instead
        name = _check_name(rec.ros_name, "msg", rec.file, rec.fq.lstrip("."))
        out.append(
            _Interface(
                rel_path=f"msg/{name}.msg",
                source=rec.file,
                blocks=[_block(rec, registry)],
            )
        )

    if services:
        for file in fdset.file:
            if file.name not in target_names:
                continue
            for service in file.service:
                for method in service.method:
                    name = _check_name(
                        f"{service.name}{method.name}"
                        if srv_prefix_service
                        else method.name,
                        "srv",
                        file.name,
                        f"{service.name}.{method.name}",
                    )
                    out.append(
                        _Interface(
                            rel_path=f"srv/{name}.srv",
                            source=file.name,
                            blocks=[
                                _block(registry.by_fq[method.input_type], registry),
                                _block(registry.by_fq[method.output_type], registry),
                            ],
                        )
                    )

    _check_unique(out)
    return sorted(out, key=lambda i: i.rel_path)


