"""protofiles -> ROS2 `.msg` / `.srv` interface definitions.

Compiles the target protos to a FileDescriptorSet with the protoc bundled in
grpc_tools (no system protoc needed, same as the producer codegen does), then
renders one `.msg` per message and one `.srv` per rpc method.

Meant to be driven from an interface package's CMakeLists at *configure* time,
so `colcon build` is the whole workflow -- there is no separate generate step to
forget and no way to build against a stale interface. Only the ament plumbing
(package.xml, CMakeLists.txt) is committed; msg/ and srv/ are generated.

The mapping is deliberately narrow: anything without a faithful ROS2 equivalent
raises Ros2GenError instead of emitting something misleading. See
render_interfaces() for the full list, both directions.
"""

from __future__ import annotations

import fnmatch
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory

GENERATED_MARKER = "Generated by proto4webrtc_codegen.ros2"

# proto scalar type -> ROS2 interface primitive.
# Note the deliberate widenings: proto's zigzag/fixed encodings are wire
# details, not value ranges, so they collapse onto the plain ROS integer of the
# same signedness and width.
_SCALAR = {
    descriptor_pb2.FieldDescriptorProto.TYPE_DOUBLE: "float64",
    descriptor_pb2.FieldDescriptorProto.TYPE_FLOAT: "float32",
    descriptor_pb2.FieldDescriptorProto.TYPE_INT64: "int64",
    descriptor_pb2.FieldDescriptorProto.TYPE_UINT64: "uint64",
    descriptor_pb2.FieldDescriptorProto.TYPE_INT32: "int32",
    descriptor_pb2.FieldDescriptorProto.TYPE_FIXED64: "uint64",
    descriptor_pb2.FieldDescriptorProto.TYPE_FIXED32: "uint32",
    descriptor_pb2.FieldDescriptorProto.TYPE_BOOL: "bool",
    descriptor_pb2.FieldDescriptorProto.TYPE_STRING: "string",
    descriptor_pb2.FieldDescriptorProto.TYPE_UINT32: "uint32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED32: "int32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED64: "int64",
    descriptor_pb2.FieldDescriptorProto.TYPE_SINT32: "int32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SINT64: "int64",
}

_BYTES = descriptor_pb2.FieldDescriptorProto.TYPE_BYTES
_MESSAGE = descriptor_pb2.FieldDescriptorProto.TYPE_MESSAGE
_ENUM = descriptor_pb2.FieldDescriptorProto.TYPE_ENUM
_LABEL_REPEATED = descriptor_pb2.FieldDescriptorProto.LABEL_REPEATED

MEDIA_STREAM_EXT = "proto4webrtc.media_stream"

# ROS2 field names: lowercase, underscore-separated, no leading/trailing or
# doubled underscores. protoc already rejects most of what would break this, but
# `myField` is legal proto and illegal here.
_ROS_FIELD_RE = re.compile(r"^[a-z](?:_?[a-z0-9])*$")

# Interface (file) names are CamelCase; constants are UPPER_SNAKE. Both are
# rosidl rules rather than ours -- catching them here turns an opaque
# mid-`colcon build` failure into an error naming the .proto to edit.
_ROS_TYPE_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")
_ROS_CONST_RE = re.compile(r"^[A-Z](?:_?[A-Z0-9])*$")

# rosidl generates C++ and Python from every field name, so a field that is a
# keyword in either language builds a package that will not compile. protoc
# accepts all of them.
_RESERVED_FIELD_NAMES = frozenset(
    {
        # C++
        "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case",
        "catch", "char", "class", "const", "constexpr", "continue", "decltype",
        "default", "delete", "do", "double", "dynamic_cast", "else", "enum",
        "explicit", "export", "extern", "false", "float", "for", "friend",
        "goto", "if", "inline", "int", "long", "mutable", "namespace", "new",
        "noexcept", "not", "nullptr", "operator", "or", "private", "protected",
        "public", "register", "return", "short", "signed", "sizeof", "static",
        "static_cast", "struct", "switch", "template", "this", "throw", "true",
        "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
        "virtual", "void", "volatile", "while", "xor",
        # Python-only additions
        "and_", "as", "assert", "async", "await", "def", "del", "elif",
        "except", "finally", "from", "global", "import", "in", "is", "lambda",
        "nonlocal", "pass", "raise", "with", "yield",
    }
)

OPTIONS_PROTO = "proto4webrtc/options.proto"


class Ros2GenError(RuntimeError):
    """A proto construct that has no faithful ROS2 interface equivalent."""


@dataclass
class _Field:
    ros_type: str  # e.g. "float64", "uint8[]", "MissionWaypoint"
    name: str
    # Set when the field was a proto enum: the values become a constants block.
    enum: tuple[str, tuple[tuple[str, int], ...]] | None = None


@dataclass
class _Block:
    """One rendered field block: the constants it needs, then its fields."""

    fields: list[_Field] = field(default_factory=list)


@dataclass
class _Interface:
    rel_path: str  # e.g. "msg/Thrusters.msg" or "srv/Ping.srv"
    source: str  # originating .proto path, for the generated header
    blocks: list[_Block]  # one block for a msg; request then response for a srv


@dataclass
class _MsgRec:
    """A proto message that has (or would have) a ROS2 counterpart."""

    desc: descriptor_pb2.DescriptorProto
    fq: str  # ".rov.streams.PointCloud"
    ros_name: str  # "PointCloud"; nested types flatten (MissionWaypoint)
    file: str  # "rov/streams/pointcloud.proto"


